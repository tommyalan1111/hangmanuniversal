  function stableId(category, question, answer) {
    var key = category + '|' + question + '|' + answer;
    var h = 2166136261;
    for (var i = 0; i < key.length; i++) {
      h ^= key.charCodeAt(i);
      h = Math.imul(h, 16777619);
    }
    return category + '-' + (h >>> 0).toString(36);
  }

